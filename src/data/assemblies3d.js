export function matchAssemblyForRevit({ category = "", family = "", typeName = "", query = "" } = {}) {
  const hay = `${category} ${family} ${typeName} ${query}`.toLowerCase();
  if (!hay.trim()) return ASSEMBLIES_3D[0];
  let best = null;
  let bestScore = 0;
  for (const asm of ASSEMBLIES_3D) {
    let score = 0;
    if (category && asm.revitCategory.toLowerCase() === category.toLowerCase()) score += 3;
    for (const kw of asm.keywords) {
      if (hay.includes(kw)) score += 4;
    }
    if (hay.includes(asm.revitType.toLowerCase())) score += 10;
    if (score > bestScore) {
      bestScore = score;
      best = asm;
    }
  }
  return bestScore > 0 ? best : null;
}
